import AppKit

/// Rules for which pasteboard types to keep.
///
/// The rules and their order are mostly copied from Clipy and Maccy. Each one corresponds to a
/// real problem, and the comments say which.
public enum PasteboardTypes {
    // MARK: Markers that skip the whole clip

    /// Password managers use this to mark passwords; see http://nspasteboard.org
    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    /// Transient content that shouldn't enter the history
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    /// Generated automatically by a program rather than copied by the user
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// The three markers that skip the whole clip.
    ///
    /// Our own writes back to the pasteboard aren't handled here. Those are recognised by
    /// changeCount: after writing we note the number, and the next tick skips it when it sees the
    /// same number. A marker stamped onto the content would be passed along as-is by other tools,
    /// and that content could never enter the history again.
    static let skipEntireClip: Set<NSPasteboard.PasteboardType> = [
        concealed, transient, autoGenerated,
    ]

    // MARK: Special types

    /// Universal Clipboard
    public static let universalClipboard = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")
    static let microsoftObjectLink = NSPasteboard.PasteboardType("com.microsoft.ObjectLink")
    static let microsoftLinkSource = NSPasteboard.PasteboardType("com.microsoft.Link-Source")
    /// AppKit has no constant for JPEG, so define one
    public static let jpeg = NSPasteboard.PasteboardType("public.jpeg")

    /// The legacy multi-file type; it's the only one that has to be written at the pasteboard root
    public static let legacyFilenames = NSPasteboard.PasteboardType("NSFilenamesPboardType")

    // MARK: Preserved order
    //
    // Types are laid out in this order when written back. Some apps pick which representation to use
    // by the order of types on the pasteboard, and a scrambled order may make them choose plain text
    // over rich text. Richer types go first.

    public static let preferredOrder: [NSPasteboard.PasteboardType] = [
        .rtfd, .rtf, .html, .png, jpeg, .tiff, .pdf, .fileURL, legacyFilenames, .URL, .string,
    ]

    /// Legacy alias → modern type. The same data on the pasteboard often carries both names:
    /// `public.rtf` and `NeXT Rich Text Format v1.0 pasteboard type` are the same bytes.
    /// Storing both just doubles the size for nothing.
    static let modernEquivalent: [String: NSPasteboard.PasteboardType] = [
        "NSStringPboardType": .string,
        "NeXT Rich Text Format v1.0 pasteboard type": .rtf,
        "NeXT RTFD pasteboard type": .rtfd,
        "Apple HTML pasteboard type": .html,
        "Apple PDF pasteboard type": .pdf,
        "Apple PNG pasteboard type": .png,
        "NeXT TIFF v4.0 pasteboard type": .tiff,
        "NSFilenamesPboardType": .fileURL,
        "Apple URL pasteboard type": .URL,
        "Apple Web Archive pasteboard type": webArchive,
        "CorePasteboardFlavorType 0x75743136": .string,
        // The icon Finder attaches when copying files; the old name is its four-char code 'icns'
        "CorePasteboardFlavorType 0x69636E73": .init("com.apple.icns"),
    ]

    /// Apps written with Qt put content under their own wrapper type:
    /// `com.trolltech.anymime.<type>--<subtype>`, i.e. the MIME slash replaced by two hyphens.
    /// WPS does this: it **doesn't send** `public.rtf` at all, only `com.trolltech.anymime.text--rtf`.
    /// Stored under the original name, nothing recognises it when pasted into TextEdit, Word or
    /// Notes, so the rich text is kept for nothing.
    ///
    /// The bytes themselves are in the standard format, so storing them under another name is
    /// enough. Only the types whose **format really is identical** are renamed: plain text isn't
    /// among them, since renaming `public.utf16-plain-text` to utf8 would garble the text outright.
    static let wrappedEquivalent: [String: NSPasteboard.PasteboardType] = [
        "com.trolltech.anymime.text--rtf": .rtf,
        "com.trolltech.anymime.text--html": .html,
        "com.trolltech.anymime.image--png": .png,
        "com.trolltech.anymime.application--pdf": .pdf,
    ]

    /// Which type name this data should be stored under. If the standard one is already present,
    /// leave it as-is and let `shouldStore` drop the duplicate.
    static func canonicalType(for type: NSPasteboard.PasteboardType,
                              present: Set<NSPasteboard.PasteboardType>) -> NSPasteboard.PasteboardType {
        guard let canonical = wrappedEquivalent[type.rawValue] ?? modernEquivalent[type.rawValue],
              !present.contains(canonical) else { return type }
        return canonical
    }

    /// Web archive. Safari and WebKit-based apps attach it when copying web content; it holds the
    /// whole page's HTML plus all its embedded subresources (images, style sheets).
    public static let webArchive = NSPasteboard.PasteboardType("com.apple.webarchive")

    /// Size cap for a single type. Over the cap, that one representation is dropped and the rest
    /// are kept.
    ///
    /// Originally the only cut was "if the whole clip is over 5 MB, reduce it to plain text", which
    /// is too blunt: a 2.3 MB clip gets past it and is kept whole. In one measurement, copying
    /// 35 characters from a web page gave 661 bytes of HTML but a 2.3 MB web archive, because it
    /// bundles the whole page's subresources, not the part you selected. Four clips like that took
    /// up 65% of the entire database.
    ///
    /// It isn't worthless: images in the HTML are referenced by address, and the web archive is the
    /// representation that actually embeds them. So no blanket ban; a cap, and small ones are kept.
    static let sizeCaps: [NSPasteboard.PasteboardType: Int] = [
        webArchive: 256 * 1024,
    ]

    /// Type prefixes that are never stored.
    /// `dyn.` is a dynamic code the system makes up for unregistered types, which only the source
    /// app understands; the Microsoft one is Office's internal source marker;
    /// `org.chromium.internal.` is Chrome's own session token. It says internal right in the name
    /// and means nothing outside that browser process.
    static let ignoredPrefixes = [
        "dyn.", "com.microsoft.ole.source.", "org.chromium.internal.",
    ]

    /// Is this type worth storing?
    static func shouldStore(_ type: NSPasteboard.PasteboardType,
                            alongside all: Set<NSPasteboard.PasteboardType>) -> Bool {
        let raw = type.rawValue
        if ignoredPrefixes.contains(where: raw.hasPrefix) { return false }
        if skipEntireClip.contains(type) { return false }
        if type == universalClipboard { return false }

        // Legacy alias: don't store it if the modern type is also present
        if let modern = modernEquivalent[raw], all.contains(modern), modern != type {
            return false
        }
        // Don't store TIFF if there's a PNG or JPEG. TIFF is uncompressed, and when only a JPEG is put
        // on the pasteboard the system automatically synthesises a TIFF next to it. Measured: a 33 KB
        // JPEG came with a 123 KB synthesised TIFF, and storing both is pure waste.
        if type == .tiff, all.contains(.png) || all.contains(jpeg) { return false }
        // Word bookmarks and cross-references stuff in a pile of useless data (p0deje/Maccy#613, #770)
        if type == .pdf, all.contains(microsoftLinkSource), all.contains(microsoftObjectLink) {
            return false
        }
        if type == microsoftLinkSource || type == microsoftObjectLink { return false }
        return true
    }
}
