import AppKit

public enum PasteboardReader {
    // Kept for older call sites
    public static let concealedType = PasteboardTypes.concealed
    public static let transientType = PasteboardTypes.transient
    public static let autoGeneratedType = PasteboardTypes.autoGenerated

    /// Size limit for a single clip. Above it, only the plain-text representation is kept.
    /// Alfred has a "maximum clipboard size" setting for exactly this: copying a whole document with
    /// images easily produces several MB of RTFD, which adds up over a few thousand clips.
    public static let maximumClipBytes = 5 * 1024 * 1024

    /// The only step done on the main thread: pull the bytes worth keeping off the pasteboard.
    ///
    /// NSPasteboard isn't thread-safe, so reads must happen on the main thread. But the work after
    /// reading (deduplication, TIFF to PNG, decoding for dimensions, extracting plain text from rich
    /// text) is heavy and slow: copying a large screenshot could stall the main thread for several
    /// hundred ms, freezing both the menu bar and the panel. So it's split in two: this half fetches
    /// the bytes, and the `capture(from:)` half can be pushed to the background.
    public static func read(from pb: NSPasteboard, acceptRemote: Bool = true) -> [ClipCapture.Asset]? {
        let allTypes = Set(pb.types ?? [])
        if !allTypes.isDisjoint(with: PasteboardTypes.skipEntireClip) { return nil }

        let isUniversalClipboard = allTypes.contains(PasteboardTypes.universalClipboard)
        if isUniversalClipboard, !acceptRemote { return nil }
        // Universal Clipboard file URLs point to an Apple-managed temporary directory; when a
        // third-party app receives them, the system may not grant a sandbox extension, so the app
        // pasting can't open the file. When the primary representation is a file URL, skip the whole clip.
        if isUniversalClipboard, pb.types?.first == .fileURL { return nil }

        let assets = collectAssets(from: pb, allTypes: allTypes, skipFileURLs: isUniversalClipboard)
        return assets.isEmpty ? nil : assets
    }

    /// Turns the fetched bytes into a history entry. All the slow work is here; safe to run on a background thread.
    public static func capture(from raw: [ClipCapture.Asset]) -> ClipCapture? {
        // Optimisations apply to representations of the SAME item. A PNG in item 0 must not
        // discard a TIFF in item 1, and equal bytes in different items are not duplicates.
        var seenItems = Set<Int?>()
        let itemOrder = raw.map(\.pasteboardItemIndex).filter { seenItems.insert($0).inserted }
        let groups = Dictionary(grouping: raw, by: \.pasteboardItemIndex)
        var assets = itemOrder.flatMap { index in
            var itemAssets = dropFileIcons(groups[index] ?? [])
            itemAssets.sort { rank(of: $0.type) < rank(of: $1.type) }
            return compressLoneTIFF(dropDuplicatePayloads(itemAssets))
        }
        assets = assets.filter { asset in
            guard let cap = PasteboardTypes.sizeCaps[asset.type] else { return true }
            return asset.data.count <= cap
        }
        guard !assets.isEmpty else { return nil }

        let filePaths = fileURLs(in: assets).map(\.path)
        let text = plainText(from: assets)
        let imageSize = imageDimensions(in: assets)

        let kind: ClipKind
        if !filePaths.isEmpty {
            kind = .file
        } else if imageSize != nil {
            kind = .image
        } else {
            kind = .text
        }

        // Text-only clips that are empty after trimming whitespace aren't recorded
        if kind == .text, text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return nil
        }

        // Oversized clips keep only plain text, so one record doesn't eat several MB
        let total = assets.reduce(0) { $0 + $1.data.count }
        if total > maximumClipBytes, kind == .text {
            assets = assets.filter { $0.type == .string }
            // The source may have offered only RTF or HTML. The text was already pulled out of it
            // above, so keep that as the plain-text form instead of dropping the whole clip.
            if assets.isEmpty { assets = [.init(type: .string, data: Data(text.utf8))] }
        }

        return ClipCapture(assets: assets, kind: kind, text: text,
                           imageSize: imageSize, filePaths: filePaths)
    }

    /// The all-in-one version, used by tests and single-process call sites.
    public static func capture(from pb: NSPasteboard, acceptRemote: Bool = true) -> ClipCapture? {
        guard let raw = read(from: pb, acceptRemote: acceptRemote) else { return nil }
        return capture(from: raw)
    }

    // MARK: Internals

    private static func rank(of type: NSPasteboard.PasteboardType) -> Int {
        PasteboardTypes.preferredOrder.firstIndex(of: type) ?? PasteboardTypes.preferredOrder.count
    }

    /// Drops identical bytes stored under a different name.
    ///
    /// Qt apps put the same image on both `public.png` and their own
    /// `com.trolltech.anymime.image--png`, with byte-identical data. In one real library three such
    /// images took 1.3 MB, nearly a quarter of the assets directory.
    ///
    /// Only drops types **not in `preferredOrder`**. When copying a link, `public.url` and
    /// `public.utf8-plain-text` also have identical bytes, but receivers like Finder look
    /// specifically for `public.url`, so dropping it as a duplicate would genuinely break things.
    private static func dropDuplicatePayloads(_ assets: [ClipCapture.Asset]) -> [ClipCapture.Asset] {
        var kept: [ClipCapture.Asset] = []
        for asset in assets {
            let canonical = PasteboardTypes.preferredOrder.contains(asset.type)
            if !canonical, kept.contains(where: { $0.data == asset.data }) { continue }
            kept.append(asset)
        }
        return kept
    }

    /// File icons that Finder attaches when copying files are not stored.
    ///
    /// Measured: copying a 10-byte txt also puts an 850 KB icns and a 4 MB TIFF icon on the
    /// pasteboard (still 200 KB as PNG). That's an extra 1 MB for every file copy, while Settings
    /// says files "only store the path and take almost no space". Nobody uses the icons: pasting
    /// into Finder, a chat box or a document, the receiver wants the file itself.
    ///
    /// Only dropped when `com.apple.icns` and a file URL are both present, which means the images are
    /// icons drawn by the file manager. When another app puts "file URL + image", the image may be the content.
    static let fileIconType = NSPasteboard.PasteboardType("com.apple.icns")

    private static func dropFileIcons(_ assets: [ClipCapture.Asset]) -> [ClipCapture.Asset] {
        let types = Set(assets.map(\.type))
        guard types.contains(.fileURL), types.contains(fileIconType) else { return assets }
        return assets.filter { $0.type != fileIconType && PasteFormat.group(for: $0.type) != .image }
    }

    /// When TIFF is the only representation, store it as PNG instead.
    ///
    /// TIFF is an uncompressed bitmap. Measured on the same 200×200 image: TIFF 160 KB, PNG 5.5 KB,
    /// a 29x difference; large images like screenshots are even worse. PNG is lossless too, so not a
    /// pixel is lost, and no receiver accepts TIFF but not PNG. When PNG or JPEG is present, TIFF was
    /// already dropped in shouldStore, so anything reaching here is the "TIFF only" case.
    private static func compressLoneTIFF(_ assets: [ClipCapture.Asset]) -> [ClipCapture.Asset] {
        guard let index = assets.firstIndex(where: { $0.type == .tiff }),
              !assets.contains(where: { $0.type == .png || $0.type == PasteboardTypes.jpeg }),
              let rep = NSBitmapImageRep(data: assets[index].data),
              let png = rep.representation(using: .png, properties: [:]),
              png.count < assets[index].data.count else { return assets }
        var out = assets
        out[index] = .init(type: .png, data: png,
                           pasteboardItemIndex: assets[index].pasteboardItemIndex)
        return out
    }

    private static func collectAssets(from pb: NSPasteboard,
                                      allTypes: Set<NSPasteboard.PasteboardType>,
                                      skipFileURLs: Bool) -> [ClipCapture.Asset] {
        var assets: [ClipCapture.Asset] = []
        var seen = Set<String>()

        // Read per item first. Some apps put two items on the pasteboard for one copy (BBEdit, Edge),
        // and looking only at the pasteboard root misses one of them.
        for (index, item) in (pb.pasteboardItems ?? []).enumerated() {
            let types = Set(item.types)
            for type in item.types {
                guard PasteboardTypes.shouldStore(type, alongside: types) else { continue }
                if skipFileURLs, type == .fileURL { continue }
                guard let data = item.data(forType: type), !data.isEmpty else { continue }
                // Store under the standard type name, otherwise RTF from Qt apps isn't recognised by anyone
                let stored = PasteboardTypes.canonicalType(for: type, present: types)
                let key = "\(index)|\(stored.rawValue)"
                guard seen.insert(key).inserted else { continue }
                assets.append(.init(type: stored, data: data, pasteboardItemIndex: index))
            }
        }

        // Then fall back to the root level. Types like .tiff may only exist there.
        //
        // The comparison must use the type **after renaming**. The per-item pass stored Qt's
        // com.trolltech.anymime.text--rtf as public.rtf; comparing by the original name here would
        // think it hadn't been stored yet, and the same 15 KB of RTF would be stored twice.
        var itemTypes = Set(assets.map(\.type))
        for type in allTypes {
            let stored = PasteboardTypes.canonicalType(for: type, present: allTypes)
            guard !itemTypes.contains(stored) else { continue }
            guard PasteboardTypes.shouldStore(type, alongside: allTypes) else { continue }
            if skipFileURLs, type == .fileURL { continue }
            guard let data = pb.data(forType: type), !data.isEmpty else { continue }
            itemTypes.insert(stored)
            assets.append(.init(type: stored, data: data, pasteboardItemIndex: 0))
        }
        return assets
    }

    private static func fileURLs(in assets: [ClipCapture.Asset]) -> [URL] {
        assets.filter { $0.type == .fileURL }
            .compactMap { URL(dataRepresentation: $0.data, relativeTo: nil, isAbsolute: true) }
    }

    private static func imageDimensions(in assets: [ClipCapture.Asset]) -> CGSize? {
        for type in [NSPasteboard.PasteboardType.png, PasteboardTypes.jpeg, .tiff] {
            if let data = assets.first(where: { $0.type == type })?.data,
               let rep = NSBitmapImageRep(data: data) {
                return CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
            }
        }
        return nil
    }

    /// Plain text for searching and display.
    /// Empty plain text doesn't mean no content: the rich-text representations may have text, so fall back to extracting from them in turn.
    private static func plainText(from assets: [ClipCapture.Asset]) -> String {
        // Must go through **all** plain-text representations, not just the first:
        // some apps put two items on the pasteboard for one copy (BBEdit, Edge), and the first may be empty.
        for asset in assets where asset.type == .string {
            if let text = String(data: asset.data, encoding: .utf8),
               !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                return text
            }
        }
        if let data = assets.first(where: { $0.type == .rtfd })?.data,
           let attributed = NSAttributedString(rtfd: data, documentAttributes: nil),
           !attributed.string.isEmpty {
            return attributed.string
        }
        if let data = assets.first(where: { $0.type == .rtf })?.data,
           let attributed = NSAttributedString(rtf: data, documentAttributes: nil),
           !attributed.string.isEmpty {
            return attributed.string
        }
        if let data = assets.first(where: { $0.type == .html })?.data,
           let text = htmlText(data), !text.isEmpty {
            return text
        }
        return ""
    }

    /// The HTML importer goes through WebKit and must run on the main thread, while capture runs on
    /// the capture queue. Off the main thread it hops over synchronously: the main thread never waits
    /// on the capture queue, so this can't deadlock, and the case is rare (only clips that carry HTML
    /// but no plain text reach it).
    ///
    /// UTF-8 is stated explicitly, the same as the preview's renderer: without it, HTML that has no
    /// charset `<meta>` is read in a legacy encoding and non-ASCII text comes out garbled.
    private static func htmlText(_ data: Data) -> String? {
        let parse = {
            NSAttributedString(html: data,
                               options: [.characterEncoding: String.Encoding.utf8.rawValue],
                               documentAttributes: nil)?.string
        }
        return Thread.isMainThread ? parse() : DispatchQueue.main.sync(execute: parse)
    }
}
