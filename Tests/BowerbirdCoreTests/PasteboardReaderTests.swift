import AppKit
import XCTest
@testable import BowerbirdCore

final class PasteboardReaderTests: XCTestCase {
    private func freshPasteboard() -> NSPasteboard {
        NSPasteboard(name: NSPasteboard.Name("bowerbird.test.\(UUID().uuidString)"))
    }

    func testPlainText() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.setString("hello", forType: .string)
        XCTAssertEqual(PasteboardReader.capture(from: pb)?.text, "hello")
    }

    func testWhitespaceOnlyTextIsIgnored() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.setString("  \n\t ", forType: .string)
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    func testEmptyPasteboard() {
        let pb = freshPasteboard()
        pb.clearContents()
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    func testConcealedIsSkipped() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.declareTypes([.string, PasteboardReader.concealedType], owner: nil)
        pb.setString("secret", forType: .string)
        pb.setString("1", forType: PasteboardReader.concealedType)
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    func testTransientIsSkipped() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.declareTypes([.string, PasteboardReader.transientType], owner: nil)
        pb.setString("tmp", forType: .string)
        pb.setString("1", forType: PasteboardReader.transientType)
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    func testFileURLsWinOverText() {
        let pb = freshPasteboard()
        pb.clearContents()
        let url = URL(fileURLWithPath: "/tmp/bowerbird-test.txt")
        pb.writeObjects([url as NSURL])
        pb.setString("bowerbird-test.txt", forType: .string)
        XCTAssertEqual(PasteboardReader.capture(from: pb)?.filePaths, [url.path])
    }

    func testPNGImage() throws {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 3, pixelsHigh: 2, bitsPerSample: 8,
                                   samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                   colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        let png = rep.representation(using: .png, properties: [:])!
        let pb = freshPasteboard()
        pb.clearContents()
        pb.setData(png, forType: .png)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))
        XCTAssertEqual(capture.kind, .image)
        XCTAssertEqual(capture.data(for: .png), png)
        XCTAssertEqual(capture.imageSize, CGSize(width: 3, height: 2))
    }

    func testAutoGeneratedIsSkipped() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.declareTypes([.string, PasteboardReader.autoGeneratedType], owner: nil)
        pb.setString("generated", forType: .string)
        pb.setString("1", forType: PasteboardReader.autoGeneratedType)
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    func testOwnWriteIsSkipped() {
        let pb = freshPasteboard()
        pb.clearContents()
        pb.declareTypes([.string, PasteboardReader.autoGeneratedType], owner: nil)
        pb.setString("pasted back by us", forType: .string)
        pb.setString("", forType: PasteboardReader.autoGeneratedType)
        XCTAssertNil(PasteboardReader.capture(from: pb))
    }

    /// BBEdit and Edge put two items on the pasteboard per copy, and the first may be empty.
    /// Looking only at the first item loses the content.
    func testPicksTextFromLaterItemWhenFirstIsEmpty() {
        let pb = freshPasteboard()
        pb.clearContents()
        let empty = NSPasteboardItem()
        empty.setString("   ", forType: .string)
        let real = NSPasteboardItem()
        real.setString("actual content", forType: .string)
        pb.writeObjects([empty, real])
        XCTAssertEqual(PasteboardReader.capture(from: pb)?.text, "actual content")
    }

    /// When the plain text is empty but the rich text has content, the copy shouldn't be dropped
    func testFallsBackToRichTextWhenPlainTextIsEmpty() throws {
        let attributed = NSAttributedString(string: "rich only")
        let rtf = try XCTUnwrap(attributed.rtf(from: NSRange(location: 0, length: attributed.length),
                                               documentAttributes: [:]))
        let pb = freshPasteboard()
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString("", forType: .string)
        item.setData(rtf, forType: .rtf)
        pb.writeObjects([item])
        XCTAssertEqual(PasteboardReader.capture(from: pb)?.text, "rich only")
    }
    /// Qt apps put the same image under both public.png and their own type name, with identical bytes.
    /// Measured: three such images in a library wasted 1.3 MB.
    func testDropsRenamedDuplicateOfACanonicalType() throws {
        let pb = NSPasteboard(name: NSPasteboard.Name("bowerbird.dup.\(UUID().uuidString)"))
        pb.clearContents()
        let png = Self.onePixelPNG()
        pb.setData(png, forType: .png)
        pb.setData(png, forType: .init("com.trolltech.anymime.image--png"))
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.assets.map(\.type), [.png])
    }

    /// Conversely, when copying a link, public.url and the plain text are byte-for-byte identical too,
    /// but receivers such as Finder look specifically for public.url, so it can't be dropped as a
    /// duplicate.
    func testKeepsURLEvenWhenItMatchesPlainTextByteForByte() throws {
        let pb = NSPasteboard(name: NSPasteboard.Name("bowerbird.url.\(UUID().uuidString)"))
        pb.clearContents()
        let link = Data("https://example.com".utf8)
        pb.setData(link, forType: .URL)
        pb.setData(link, forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertNotNil(capture.data(for: .URL))
        XCTAssertNotNil(capture.data(for: .string))
    }

    /// Chrome's session token has "internal" right in its name and means nothing outside that process
    func testSkipsChromeInternalTypes() throws {
        let pb = NSPasteboard(name: NSPasteboard.Name("bowerbird.chrome.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setString("hello", forType: .string)
        pb.setData(Data("token".utf8), forType: .init("org.chromium.internal.source-rfh-token"))
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.assets.map(\.type), [.string])
    }

    private static func onePixelPNG() -> Data {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 1, pixelsHigh: 1,
                                   bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true,
                                   isPlanar: false, colorSpaceName: .deviceRGB,
                                   bytesPerRow: 4, bitsPerPixel: 32)!
        return rep.representation(using: .png, properties: [:])!
    }

    /// Qt apps such as WPS only publish com.trolltech.anymime.text--rtf, not public.rtf.
    /// Stored under the original name, neither TextEdit nor Word recognizes it when pasted, so the rich
    /// text is kept for nothing.
    func testRenamesQtWrappedRTFToTheStandardType() throws {
        let pb = NSPasteboard(name: .init("bowerbird.qt.\(UUID().uuidString)"))
        pb.clearContents()
        let rtf = Data("{\\rtf1\\ansi 季度报告}".utf8)
        pb.setData(rtf, forType: .init("com.trolltech.anymime.text--rtf"))
        pb.setData(Data("<b>季度报告</b>".utf8), forType: .html)
        pb.setString("季度报告", forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.data(for: .rtf), rtf, "should be stored as public.rtf")
        XCTAssertFalse(capture.assets.contains { $0.type.rawValue.hasPrefix("com.trolltech") })
        XCTAssertEqual(PasteFormat.groups(in: capture.assets).first, .richText,
                       "RTF only counts as rich text after the rename; only then does TextEdit/Word get formatting")
    }

    /// After renaming, the root-level fallback pass must not store the same data again.
    /// Measured: a 15 KB RTF from WPS was stored twice because of this.
    func testRenamedTypeIsNotStoredTwiceByTheRootFallback() throws {
        let pb = NSPasteboard(name: .init("bowerbird.dup2.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setData(Data("{\\rtf1\\ansi hi}".utf8), forType: .init("com.trolltech.anymime.text--rtf"))
        pb.setString("hi", forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.assets.filter { $0.type == .rtf }.count, 1)
    }

    /// Don't rename when the standard type is already present; let the dedup rule drop the wrapped copy
    func testKeepsStandardTypeWhenBothArePresent() throws {
        let pb = NSPasteboard(name: .init("bowerbird.qt2.\(UUID().uuidString)"))
        pb.clearContents()
        let rtf = Data("{\\rtf1\\ansi hi}".utf8)
        pb.setData(rtf, forType: .rtf)
        pb.setData(rtf, forType: .init("com.trolltech.anymime.text--rtf"))
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        // The system derives plain text from the RTF on its own, so this only asserts that the wrapped
        // copy is gone and there's exactly one standard copy
        XCTAssertEqual(capture.assets.filter { $0.type == .rtf }.count, 1)
        XCTAssertFalse(capture.assets.contains { $0.type.rawValue.hasPrefix("com.trolltech") })
    }

    /// Never rename across different plain-text encodings: storing utf16 as utf8 garbles the text
    func testNeverRenamesAcrossTextEncodings() throws {
        let pb = NSPasteboard(name: .init("bowerbird.enc.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setData("中文".data(using: .utf16)!, forType: .init("public.utf16-plain-text"))
        pb.setString("中文", forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(String(data: try XCTUnwrap(capture.data(for: .string)), encoding: .utf8), "中文")
    }

    /// A web archive bundles the whole page's subresources, not the fragment you selected. Measured:
    /// copying 35 characters from a web page gave 661 bytes of HTML and a 2.3 MB web archive, and four
    /// such items took up 65% of a library's space. Drop it above the limit; keep the other
    /// representations.
    func testDropsOversizedWebArchiveButKeepsTheRest() throws {
        let pb = NSPasteboard(name: .init("bowerbird.wa.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setData(Data(repeating: 0x41, count: 2_000_000), forType: PasteboardTypes.webArchive)
        pb.setData(Data("<b>hi</b>".utf8), forType: .html)
        pb.setString("hi", forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertNil(capture.data(for: PasteboardTypes.webArchive))
        XCTAssertNotNil(capture.data(for: .html))
        XCTAssertNotNil(capture.data(for: .string))
    }

    /// Small ones are kept: it's the only representation that actually embeds the images, so a blanket
    /// rule is wrong
    func testKeepsSmallWebArchive() throws {
        let pb = NSPasteboard(name: .init("bowerbird.wa2.\(UUID().uuidString)"))
        pb.clearContents()
        pb.setData(Data(repeating: 0x41, count: 1_000), forType: PasteboardTypes.webArchive)
        pb.setString("hi", forType: .string)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertNotNil(capture.data(for: PasteboardTypes.webArchive))
    }

    // MARK: Image formats

    private static func bitmap(_ side: Int = 200) -> NSBitmapImageRep {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: side, pixelsHigh: side,
                                   bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                   colorSpaceName: .deviceRGB, bytesPerRow: side * 4, bitsPerPixel: 32)!
        if let b = rep.bitmapData { for i in 0..<(side * side * 4) { b[i] = UInt8((i * 7919) % 251) } }
        return rep
    }

    /// When only a JPEG is on the pasteboard, the system automatically synthesizes a TIFF next to it
    /// (measured: a 33 KB JPEG came with a 123 KB TIFF). Keep only the JPEG; it's the original.
    func testJPEGOnlyKeepsJPEGAndDropsSynthesisedTIFF() throws {
        let pb = NSPasteboard(name: .init("bowerbird.jpeg.\(UUID().uuidString)"))
        pb.clearContents()
        let jpeg = Self.bitmap().representation(using: .jpeg, properties: [.compressionFactor: 0.8])!
        pb.setData(jpeg, forType: PasteboardTypes.jpeg)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.kind, .image)
        XCTAssertEqual(capture.imageSize, CGSize(width: 200, height: 200))
        XCTAssertEqual(capture.assets.map(\.type), [PasteboardTypes.jpeg])
        XCTAssertEqual(capture.data(for: PasteboardTypes.jpeg), jpeg, "the original JPEG bytes are untouched")
    }

    /// When there's only a TIFF, store it as PNG. TIFF is uncompressed; measured 160 KB vs 5.5 KB for
    /// the same image.
    ///
    /// This is a change of mind. An earlier test locked in "keep the TIFF as is; converting loses the
    /// original representation". That argument was about the bytes no longer being identical, not the
    /// pixels, and PNG is just as lossless. No receiver accepts TIFF but not PNG, so preserving the
    /// original bytes buys nothing, at the cost of every screenshot being dozens of times larger.
    func testLoneTIFFIsStoredAsPNG() throws {
        let pb = NSPasteboard(name: .init("bowerbird.tiff.\(UUID().uuidString)"))
        pb.clearContents()
        let rep = Self.bitmap()
        pb.setData(rep.tiffRepresentation!, forType: .tiff)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: pb))

        XCTAssertEqual(capture.assets.map(\.type), [.png])
        XCTAssertLessThan(capture.storedBytes, rep.tiffRepresentation!.count / 5)
        // Lossless: same dimensions when decoded back
        let back = try XCTUnwrap(NSBitmapImageRep(data: try XCTUnwrap(capture.data(for: .png))))
        XCTAssertEqual(back.pixelsWide, 200)
    }

    /// With "Save From Other Devices" turned off, text arriving via Universal Clipboard isn't recorded
    /// at all
    func testRemoteClipIsDroppedWhenNotAccepted() throws {
        let pb = NSPasteboard(name: .init("bowerbird.remote.\(UUID().uuidString)"))
        pb.clearContents()
        pb.declareTypes([.string, PasteboardTypes.universalClipboard], owner: nil)
        pb.setString("from my phone", forType: .string)
        pb.setData(Data(), forType: PasteboardTypes.universalClipboard)
        XCTAssertNil(PasteboardReader.capture(from: pb, acceptRemote: false))
        XCTAssertNotNil(PasteboardReader.capture(from: pb, acceptRemote: true))
    }

    /// HTML-only clips are read on the capture queue, but the HTML importer is main-thread only.
    /// The text must still come out, and come out as UTF-8 even without a charset `<meta>`.
    func testHTMLOnlyClipIsReadFromTheCaptureQueue() {
        let html = Data("<p>Grüße, 你好</p>".utf8)
        let done = expectation(description: "captured")
        var text: String?
        DispatchQueue.global().async {
            text = PasteboardReader.capture(from: [.init(type: .html, data: html)])?.text
            done.fulfill()
        }
        wait(for: [done], timeout: 10)
        XCTAssertEqual(text?.trimmingCharacters(in: .whitespacesAndNewlines), "Grüße, 你好")
    }

    /// An oversized clip keeps only plain text. When the source offered no plain text at all, the text
    /// pulled out of the RTF is kept instead of the whole clip being dropped.
    func testOversizedRichOnlyClipKeepsItsText() throws {
        let body = String(repeating: "long paragraph ", count: 20)
        let source = NSAttributedString(string: body, attributes: [.font: NSFont.boldSystemFont(ofSize: 12)])
        var rtf = try XCTUnwrap(source.rtf(from: NSRange(location: 0, length: source.length), documentAttributes: [:]))
        // Pad inside an RTF comment group so the document stays valid but exceeds the limit
        let padding = "{\\*\\bowerbirdpad " + String(repeating: "x", count: PasteboardReader.maximumClipBytes) + "}"
        rtf.insert(contentsOf: Data(padding.utf8), at: rtf.count - 1)
        let capture = try XCTUnwrap(PasteboardReader.capture(from: [.init(type: .rtf, data: rtf)]))
        XCTAssertEqual(capture.assets.map(\.type), [.string])
        XCTAssertEqual(capture.text, body)
    }
}

extension PasteboardReaderTests {
    /// Some apps offer text only as UTF-16. The pasteboard server derives the UTF-8 form on its own,
    /// so the clip is still recorded with the right characters.
    func testTextOfferedOnlyAsUTF16IsRecorded() {
        let pb = NSPasteboard.withUniqueName()
        defer { pb.releaseGlobally() }
        pb.declareTypes([.init("public.utf16-plain-text")], owner: nil)
        pb.setData("héllo 你好".data(using: .utf16)!, forType: .init("public.utf16-plain-text"))
        XCTAssertEqual(PasteboardReader.capture(from: pb)?.text, "héllo 你好")
    }
}
